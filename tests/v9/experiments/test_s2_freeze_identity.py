import pytest

from ainerzero.v9.experiments.s2 import commands, freeze, identity, prereg


def _find_repo_root() -> Path:
    current = Path(__file__).resolve()
    for p in [current] + list(current.parents):
        if (p / "pyproject.toml").is_file():
            return p
    return Path("/Users/mac/AinerWorkFlow/AinerZero")


def _make_staged_repo(tmp_path: Path) -> Path:
    """Stage a minimal repo copy under tmp_path with s2 files and cli.py."""
    staged = tmp_path / "staged_repo"
    s2_dest = staged / "src" / "ainerzero" / "v9" / "experiments" / "s2"
    s2_dest.mkdir(parents=True, exist_ok=True)

    real_root = _find_repo_root()
    real_s2 = real_root / "src" / "ainerzero" / "v9" / "experiments" / "s2"
    for f in real_s2.glob("*.py"):
        shutil.copy2(f, s2_dest / f.name)

    cli_dest = staged / "src" / "ainerzero"
    cli_dest.mkdir(parents=True, exist_ok=True)
    shutil.copy2(real_root / "src" / "ainerzero" / "cli.py", cli_dest / "cli.py")
    shutil.copy2(real_root / "pyproject.toml", staged / "pyproject.toml")
    return staged


def test_freeze_then_verify_passes_and_detects_single_byte_tamper(tmp_path: Path) -> None:
    """Freeze document, verify it passes, then modify one byte of worker.py and assert failure."""
    staged = _make_staged_repo(tmp_path)
    draft = prereg.build_draft(repo_root=staged)
    out_dir = tmp_path / "frozen_out"

    # 1. Freeze
    doc_sha = freeze.freeze(draft, out_dir, repo_root=staged)
    assert len(doc_sha) == 64

    # 2. Verify frozen identity passes
    prereg_file = out_dir / "prereg.json"
    res = identity.verify_frozen_identity(prereg_file, repo_root=staged)
    assert res["status"] == "passed"
    assert res["document_sha256"] == doc_sha
    assert "src/ainerzero/v9/experiments/s2/worker.py" in res["source_digests"]

    # 3. Modify single byte of worker.py in staged repo
    worker_py = staged / "src" / "ainerzero" / "v9" / "experiments" / "s2" / "worker.py"
    orig_bytes = worker_py.read_bytes()
    worker_py.write_bytes(orig_bytes + b"\n# tamper\n")

    # 4. Identity check must fail and name worker.py
    with pytest.raises(identity.FrozenIdentityMismatchError) as exc_info:
        identity.verify_frozen_identity(prereg_file, repo_root=staged)

    err_msg = str(exc_info.value)
    assert "src/ainerzero/v9/experiments/s2/worker.py" in err_msg


def test_freeze_refuses_overwrite(tmp_path: Path) -> None:
    """Freeze refuses to overwrite an existing prereg.json or prereg.json.sha256."""
    staged = _make_staged_repo(tmp_path)
    draft = prereg.build_draft(repo_root=staged)
    out_dir = tmp_path / "overwrite_test"

    freeze.freeze(draft, out_dir, repo_root=staged)
    assert (out_dir / "prereg.json").is_file()

    # Second freeze to same target must raise FileExistsError
    with pytest.raises(FileExistsError, match="Target.*already exists"):
        freeze.freeze(draft, out_dir, repo_root=staged)


def test_prereg_tamper_detected_when_sha_unchanged(tmp_path: Path) -> None:
    """Tampering with prereg.json without updating companion .sha256 raises ValueError."""
    staged = _make_staged_repo(tmp_path)
    draft = prereg.build_draft(repo_root=staged)
    out_dir = tmp_path / "tamper_test"

    freeze.freeze(draft, out_dir, repo_root=staged)
    prereg_file = out_dir / "prereg.json"

    # Corrupt prereg.json
    text = prereg_file.read_text(encoding="utf-8")
    tampered_text = text.replace('"awaiting_coordinator_approval"', '"tampered_status"')
    prereg_file.write_text(tampered_text, encoding="utf-8")

    with pytest.raises(ValueError, match="Checksum verification failed"):
        identity.verify_frozen_identity(prereg_file, repo_root=staged)


