def test_freeze_determinism(tmp_path: Path) -> None:
    """Freezing the same draft twice into two distinct directories yields identical document_sha256."""
    staged = _make_staged_repo(tmp_path)
    draft = prereg.build_draft(repo_root=staged)

    dir_a = tmp_path / "det_a"
    dir_b = tmp_path / "det_b"

    sha_a = freeze.freeze(draft, dir_a, repo_root=staged)
    sha_b = freeze.freeze(draft, dir_b, repo_root=staged)

    assert sha_a == sha_b
    assert (dir_a / "prereg.json").read_bytes() == (dir_b / "prereg.json").read_bytes()
    assert (dir_a / "prereg.json.sha256").read_text() == (dir_b / "prereg.json.sha256").read_text()


def test_pure_cpu_isolated_subprocess() -> None:
    """Subprocess in isolated -I mode importing freeze and identity does not import MLX."""
    real_root = _find_repo_root()
    python_bin = real_root / ".venv" / "bin" / "python"
    if not python_bin.is_file():
        python_bin = Path(sys.executable)
    code = (
        "import sys\n"
        "from ainerzero.v9.experiments.s2 import freeze, identity\n"
        "assert 'mlx' not in sys.modules\n"
        "assert 'mlx.core' not in sys.modules\n"
        "assert 'mlx.nn' not in sys.modules\n"
        "print('ISOLATED_OK')\n"
    )

    res = subprocess.run(
        [str(python_bin), "-I", "-c", code],
        cwd=str(real_root),
        capture_output=True,
        text=True,
    )
    assert res.returncode == 0, f"Subprocess failed with code {res.returncode}:\n{res.stderr}"
    assert "ISOLATED_OK" in res.stdout


def test_p140_cli_snippet_tamper_detected_and_names_cli_py(tmp_path: Path) -> None:
    """冻结后改一下 cli.py 中 s2 段落的一个字节（在 tmp 伪造仓库里改），核对必须报错，并点名 src/ainerzero/cli.py:s2-phase1。

    Catches mutation P140-M1 (omitting cli.py:s2-phase1 from collect_source_digests).
    """
    staged = _make_staged_repo(tmp_path)
    draft = prereg.build_draft(repo_root=staged)
    out_dir = tmp_path / "frozen_cli_test"

    doc_sha = freeze.freeze(draft, out_dir, repo_root=staged)
    prereg_file = out_dir / "prereg.json"

    # Pre-check: passes before tampering
    res = identity.verify_frozen_identity(prereg_file, repo_root=staged)
    assert res["status"] == "passed"
    assert "src/ainerzero/cli.py:s2-phase1" in res["source_digests"]

    # Tamper 1 byte inside the s2-phase1 section of cli.py
    cli_py = staged / "src" / "ainerzero" / "cli.py"
    cli_text = cli_py.read_text(encoding="utf-8")
    assert "s2-phase1" in cli_text

    # Modify one byte in the s2 help string
    tampered_cli = cli_text.replace(
        "多时间尺度世界脑实验",
        "多时间尺度世界脑实验X",
        1,
    )
    assert tampered_cli != cli_text, "Failed to tamper s2 section in cli.py"
    cli_py.write_text(tampered_cli, encoding="utf-8")

    # Verification must fail and explicitly name src/ainerzero/cli.py:s2-phase1
    with pytest.raises(identity.FrozenIdentityMismatchError) as exc_info:
        identity.verify_frozen_identity(prereg_file, repo_root=staged)

    err_msg = str(exc_info.value)
    assert "src/ainerzero/cli.py:s2-phase1" in err_msg


def test_p140_approval_line_validation() -> None:
    """approval_line 收到 63 位、65 位、含 g 的字符串、空串，都要抛错；收到大写的 64 位十六进制时，转成小写后通过。

    Catches mutation P140-M2 (omitting approval_line hex validation).
    """
    # 1. 63 characters -> ValueError
    with pytest.raises(ValueError, match="document_sha256 must be exactly 64"):
        freeze.approval_line("a" * 63)

    # 2. 65 characters -> ValueError
    with pytest.raises(ValueError, match="document_sha256 must be exactly 64"):
        freeze.approval_line("a" * 65)

    # 3. String containing 'g' -> ValueError
    invalid_hex = ("a" * 63) + "g"
    with pytest.raises(ValueError, match="document_sha256 must be exactly 64"):
        freeze.approval_line(invalid_hex)

    # 4. Empty string -> ValueError
    with pytest.raises(ValueError, match="document_sha256 must be exactly 64"):
        freeze.approval_line("")

    # 5. Uppercase 64-character hex -> converted to lowercase and succeeds
    upper_sha = "A1B2C3D4" * 8
    line = freeze.approval_line(upper_sha)
    assert line == f"APPROVED s2-phase1 prereg document_sha256={upper_sha.lower()}"

    # 6. Leading/trailing whitespace on valid sha is stripped
    spaced_sha = f"  {upper_sha}  \n"
    line_spaced = freeze.approval_line(spaced_sha)
    assert line_spaced == f"APPROVED s2-phase1 prereg document_sha256={upper_sha.lower()}"
