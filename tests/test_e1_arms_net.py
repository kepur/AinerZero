def test_arm6_orthogonal_projection_inner_product():
    """Verify Arm 6 residual is orthogonal to Jacobian: |·| < 1e-8; failing when project=False."""
    body = ActiveBody(
        name="Ball",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=np.array([0.0, 0.0, 2.0], dtype=np.float64),
        velocity=np.array([1.0, 0.0, -0.5], dtype=np.float64),
    )
    env = StaticEnvironment(ground=None)

    # Compute 1-step Jacobian
    jac_dict = compute_prior_jacobian([body], env, num_frames=1)
    J = np.column_stack([jac_dict[p][1, 0:6] for p in PARAM_NAMES])  # (6, 5)

    raw_residual = np.array([0.15, -0.22, 0.31, 0.08, -0.12, 0.25], dtype=np.float64)

    # 1. Project = True: orthogonal projection
    proj_residual, num_truncated = project_onto_orthogonal_complement(raw_residual, J)

    dots_proj = [abs(float(np.dot(J[:, i], proj_residual))) for i in range(J.shape[1])]
    max_dot_proj = max(dots_proj)
    assert max_dot_proj < 1e-8, f"Max dot product {max_dot_proj} >= 1e-8"
    assert num_truncated >= 0

    # 2. Project = False: raw unprojected residual violates orthogonality
    dots_noproj = [abs(float(np.dot(J[:, i], raw_residual))) for i in range(J.shape[1])]
    max_dot_noproj = max(dots_noproj)
    assert max_dot_noproj > 1e-8, f"Unprojected max dot product {max_dot_noproj} unexpectedly <= 1e-8"


