def test_save_load_bitwise_consistency():
    """Verify model save and load produces exact bitwise match in predictions and parameter SHA."""
    arm1 = PureNetArm(seed=42)
    arm2 = PureNetArm(seed=999)  # initialized with different seed

    assert arm1.parameter_sha256() != arm2.parameter_sha256()

    with tempfile.NamedTemporaryFile(suffix=".safetensors") as tmp:
        arm1.save(tmp.name)
        arm2.load(tmp.name)

        assert arm1.parameter_sha256() == arm2.parameter_sha256()

        prefix = np.ones((6, 6), dtype=np.float64) * 0.3
        pred1 = arm1.predict(prefix, None, n_future=10)
        pred2 = arm2.predict(prefix, None, n_future=10)

