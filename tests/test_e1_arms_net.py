def test_r5_radius_sensitive_bouncing_ball_behavior():
    """r5 requirement 4: Prior-generated bouncing ball sensitive to radius during identification."""
    from ainerzero.v9.experiments.e1.prior import (
        ActiveBody,
        GroundPlane,
        StaticEnvironment,
        PhysicalParameters,
        rollout,
    )
    from ainerzero.v9.experiments.e1.arms_nonnet import IdentifyArm
    from ainerzero.v9.experiments.e1.train_runner import make_arm6_identifier

    radius = 0.4
    e_true = 0.6
    params = PhysicalParameters(friction=0.2, restitution=e_true, mass=1.0, linear_damping=0.0, angular_damping=0.0)
    ground = GroundPlane(z_plane=0.0, friction=0.2, restitution=e_true)
    env = StaticEnvironment(ground=ground)

    # Ball bounces on ground within first 10 frames, and bounces again in future frames
    body = ActiveBody(
        name="ball",
        radius=radius,
        params=params,
        position=np.array([0.0, 0.0, 0.5], dtype=np.float64),
        velocity=np.array([5.0, 0.0, -2.0], dtype=np.float64),
    )
    traj = rollout([body], env, num_frames=30)
    prefix_traj = traj["ball"][:10]

    # Precondition: Radius 0.4 vs 0.5 yields strictly different identified phi_hat
    arm5 = IdentifyArm()
    phi_04, _, ok_04 = arm5.identify_body("ball", prefix_traj[:, 0:6], env, radius=0.4)
    phi_05, _, ok_05 = arm5.identify_body("ball", prefix_traj[:, 0:6], env, radius=0.5)

    assert ok_04, "Identification with true radius 0.4 should succeed"
    diff_restitution = abs(phi_04.restitution - phi_05.restitution)
    diff_friction = abs(phi_04.friction - phi_05.friction)
    assert diff_restitution > 0.05 or diff_friction > 0.02, (
        f"Identification not sensitive to radius: diff_restitution={diff_restitution}, diff_friction={diff_friction}"
    )

    # Behavior: Arm 6 identifier receives true radius and matches Arm 5 identification
    id_fn = make_arm6_identifier()
    phi_arm6 = id_fn(prefix_traj[:, :6], env, geometry_by_body={"body_0": BodyGeometry(radius=radius)})
    assert abs(phi_arm6.restitution - phi_04.restitution) < 1e-6, (
        f"make_arm6_identifier restitution {phi_arm6.restitution} != {phi_04.restitution}"
    )

    # Behavior: Arm 6 zeroed network prediction matches Arm 5 to 1e-9 across future rollout (including contact)
    observed_prefix = {"ball": prefix_traj}
    geometry_by_body = {"ball": BodyGeometry(radius=radius)}

    arm6 = IdentifyResidualArm(seed=42, identifier_fn=make_arm6_identifier())
    for mod in [arm6.net.fc1, arm6.net.fc2, arm6.net.out]:
        mod.weight = mx.zeros_like(mod.weight)
        mod.bias = mx.zeros_like(mod.bias)

    pred5 = arm5.predict(observed_prefix, env, n_future=15, geometry_by_body=geometry_by_body)
    pred6 = arm6.predict(observed_prefix, env, n_future=15, geometry_by_body=geometry_by_body)

    pos5 = pred5.positions["ball"]
    pos6 = pred6["ball"][:, 0:3]
    vel5 = pred5.velocities["ball"]
    vel6 = pred6["ball"][:, 3:6]

    diff_pos = float(np.max(np.abs(pos5 - pos6)))
    diff_vel = float(np.max(np.abs(vel5 - vel6)))

    assert diff_pos < 1e-9, f"Arm 6 zeroed pos diff {diff_pos} >= 1e-9"
    assert diff_vel < 1e-9, f"Arm 6 zeroed vel diff {diff_vel} >= 1e-9"


