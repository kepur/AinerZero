"""Isolated batch check: tree = `git archive HEAD` + cumulative code batches (+ staged cli.py variant).

Usage: python3 build_tree.py <batch_name|final>
  <batch_name>  build HEAD + batches up to and including it, run that batch's tests
  final         build HEAD + all code batches, run the whole tests/ suite

Writes ONLY under this script's directory (tree_<name>/, logs/). The live repo is read via
`git archive` / `git ls-files` / file copies. Because some project code anchors paths at the
registered host root, the run also (a) records every live path opened in-process, with write
modes and sqlite connects, and (b) stats the live tree before and after to detect any write,
including from subprocesses.
"""
import glob, hashlib, io, json, os, shutil, subprocess, sys, tarfile, time

sys.path.insert(0, os.path.dirname(__file__))
from batches import CODE_BATCHES, CLI_VARIANT, REPO, all_batches  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
LOGS = os.path.join(HERE, "logs")
SNAP_DIRS = ["artifacts", "reports", "src", "tests", "scripts", "contracts", "docs", "envs/teachers/t6"]


def live_snapshot():
    snap = {}
    for name in os.listdir(REPO):
        p = os.path.join(REPO, name)
        if os.path.isfile(p):
            st = os.stat(p); snap[name] = (st.st_mtime_ns, st.st_size)
    for d in SNAP_DIRS:
        for root, dirs, files in os.walk(os.path.join(REPO, d)):
            dirs[:] = [x for x in dirs if x not in ("__pycache__", ".pytest_cache")]
            for f in files:
                p = os.path.join(root, f)
                try:
                    st = os.lstat(p)
                except OSError:
                    continue
                snap[os.path.relpath(p, REPO)] = (st.st_mtime_ns, st.st_size)
    return snap


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# Machine-local environment that can never be committed (weights, venv, third-party checkout).
# Overlaid as symlinks only for the "--env" variant, to separate environment gaps from defects.
ENV_OVERLAY_TEACHERS = ["artifacts/teachers/da3", "envs/teachers/.venv-t6", "envs/teachers/t6/Depth-Anything-3",
                        "reports/V9-T35/predictions/**/*.safetensors"]
# The old M2 evidence store is needed only by the full suite. CAUTION (2026-11-05 final --env run):
# some tracked M2 tests write their outputs into artifacts/reports/E25-weighted and E27-onestep, so a
# symlinked overlay lets them rewrite live files (content was regenerated byte-identically; see PLAN.md).
ENV_OVERLAY_FULL = ENV_OVERLAY_TEACHERS + ["artifacts/reports", "artifacts/pilot"]
ENV_OVERLAY = ENV_OVERLAY_TEACHERS


def build(upto, env=False):
    global ENV_OVERLAY
    ENV_OVERLAY = ENV_OVERLAY_FULL if upto == "final" else ENV_OVERLAY_TEACHERS
    tag = upto + ("_env" if env else "")
    tree = os.path.join(HERE, f"tree_{tag}")
    if os.path.exists(tree):
        shutil.rmtree(tree)
    os.makedirs(tree)
    data = subprocess.run(["git", "-C", REPO, "archive", "--format=tar", "HEAD"], capture_output=True, check=True).stdout
    tarfile.open(fileobj=io.BytesIO(data)).extractall(tree, filter="fully_trusted")
    seq, _ = all_batches()
    batch_files = {}
    for name, desc, fs in seq:
        batch_files[name] = fs
        for f in fs:
            dst = os.path.join(tree, f)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(REPO, f), dst)
        if name in CLI_VARIANT:
            shutil.copy2(os.path.join(HERE, CLI_VARIANT[name]), os.path.join(tree, "src/ainerzero/cli.py"))
        if name == upto:
            break
    if env:
        rels = []
        for entry in ENV_OVERLAY:
            rels += ([os.path.relpath(p, REPO) for p in glob.glob(os.path.join(REPO, entry), recursive=True)]
                     if "*" in entry else [entry])
        for rel in rels:
            dst = os.path.join(tree, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if os.path.lexists(dst):
                raise SystemExit(f"overlay target already in tree: {rel}")
            os.symlink(os.path.join(REPO, rel), dst)
    return tree, batch_files, tag


def main(upto, env=False):
    os.makedirs(LOGS, exist_ok=True)
    t0 = time.time()
    before = live_snapshot()
    tree, bf, tag = build(upto, env)
    if upto == "final":
        expanded = [os.path.join(tree, "tests")]
    else:
        tests = next(t for n, d, sp, t in CODE_BATCHES if n == upto)
        expanded = []
        for t in tests:
            expanded += sorted(glob.glob(os.path.join(tree, t))) if "*" in t else [os.path.join(tree, t)]
    log = os.path.join(LOGS, f"live_opens_{tag}.json")
    env = dict(os.environ, PYTHONPATH=os.path.join(tree, "src"), LIVE_OPEN_LOG=log, TREE=tree,
               PYTHONDONTWRITEBYTECODE="1")
    cmd = [f"{REPO}/.venv/bin/python", os.path.join(HERE, "hook_pytest.py"), "-q", "-rfEs", "-p", "no:cacheprovider",
           f"--junitxml={os.path.join(LOGS, f'junit_{tag}.xml')}", *expanded]
    r = subprocess.run(cmd, cwd=tree, env=env, capture_output=True, text=True)
    with open(os.path.join(LOGS, f"pytest_{tag}.txt"), "w", encoding="utf-8") as fh:
        fh.write(r.stdout + "\n--- stderr ---\n" + r.stderr)
    after = live_snapshot()
    changed = sorted(k for k in set(before) | set(after) if before.get(k) != after.get(k))

    tracked = set(subprocess.run(["git", "-C", REPO, "-c", "core.quotepath=off", "ls-files", "-z"],
                                 capture_output=True, text=True).stdout.split("\0"))
    inb = set(f for fs in bf.values() for f in fs)
    audit = json.load(open(log))
    opened = audit["opened"]
    overlay_prefixes = tuple(e.split("*")[0] for e in ENV_OVERLAY) if env else ()
    overlay_reads = [p for p in opened if overlay_prefixes and p.startswith(overlay_prefixes)]
    gaps = [p for p in opened if p not in tracked and p not in inb and p not in overlay_reads
            and not p.startswith(("artifacts/", ".pytest_cache"))]
    arts = [p for p in opened if p.startswith("artifacts/")]
    summary = {
        "batch": upto, "env_overlay": ENV_OVERLAY if env else [], "head": subprocess.run(["git", "-C", REPO, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip(),
        "started": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(t0)), "seconds": round(time.time() - t0, 1),
        "pytest_exit": r.returncode, "pytest_tail": r.stdout.strip().splitlines()[-1:] if r.stdout.strip() else [],
        "batch_file_counts": {k: len(v) for k, v in bf.items()},
        "inherited_sigint": audit["inherited_sigint"],
        "live_opens": len(opened), "env_overlay_reads": len(overlay_reads), "artifact_reads": arts, "gaps_untracked_not_in_batch": gaps,
        "live_write_mode_opens": audit["write_mode_opens"], "live_sqlite_connects": audit["sqlite_connects"],
        "live_tree_changed_during_run": changed,
        "cli_variant": CLI_VARIANT.get(upto, "HEAD" if upto != "final" else "cli_all.py"),
    }
    with open(os.path.join(LOGS, f"summary_{tag}.json"), "w", encoding="utf-8") as fh:
        json.dump(summary, fh, ensure_ascii=False, indent=1)
    with open(os.path.join(LOGS, f"files_{tag}.tsv"), "w", encoding="utf-8") as fh:
        for name, fs in bf.items():
            for f in fs:
                fh.write(f"{name}\t{os.path.getsize(os.path.join(REPO, f))}\t{sha(os.path.join(REPO, f))}\t{f}\n")
    print("\n".join(r.stdout.strip().splitlines()[-30:]))
    print("exit", r.returncode, "| seconds", summary["seconds"])
    print("live opens:", len(opened), "| artifacts reads:", len(arts), "| GAPS:", len(gaps),
          "| write-mode live opens:", len(audit["write_mode_opens"]), "| sqlite live:", len(audit["sqlite_connects"]),
          "| live files changed during run:", len(changed))
    for g in gaps[:40]:
        print("  GAP", g)
    for w in audit["write_mode_opens"]:
        print("  WRITE", w)
    for s in audit["sqlite_connects"]:
        print("  SQLITE", s)
    for c in changed[:40]:
        print("  CHANGED", c, before.get(c), after.get(c))


if __name__ == "__main__":
    main(sys.argv[1], env="--env" in sys.argv[2:])
