"""B5: GridLab public-observation tracking baselines (B4 scheme; pure CPU, no learning).

Input boundary: each frame the tracker receives only the public observation keys
``step, agent_xy, last_action, view, visible_objects`` (``public_view`` drops every
other key). A detection is the anonymous local appearance plus relative offset,
converted to a world cell (agent_xy + offset). Track ids are generated by the
tracker on first sight and are unrelated to private object ids. The tracker never
sees private state, velocities, future frames, hidden terrain or S05 EntityTracks.

Baselines (fixed, no tuning):
* ``current_only``: a new track for every detection every frame, no association.
* ``last_seen_nn``: keeps the last seen cell; associates by same appearance and L1.
* ``constant_velocity_nn``: velocity from the last two sightings, extrapolated by the
  integer tick gap (single sighting -> zero velocity), then same-appearance L1.

Association: one-to-one, exhaustive over small object counts; maximise the number of
matches, then minimise the total L1, then a deterministic tie-break by public
detection order and the tracker's own track sequence. Hard gate: same appearance
and L1 <= 2 cells. Unmatched detections start new tracks. A track keeps predicting
for up to 8 unseen ticks; on the 9th consecutive unseen tick it is lost; the reason for not seeing it is always ``unobserved``.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field

VERSION = "gridlab_public_tracking_baselines_v1"
PUBLIC_KEYS = ("step", "agent_xy", "last_action", "view", "visible_objects")
ASSOCIATION_L1_MAX = 2
RETENTION_TICKS = 8
BASELINES = ("current_only", "last_seen_nn", "constant_velocity_nn")


def public_view(observation: dict) -> dict:
    """Only the registered public keys; anything else (private, ids, velocity) is dropped."""
    missing = [k for k in ("step", "agent_xy", "visible_objects") if k not in observation]
    if missing:
        raise ValueError(f"public observation lacks {missing}")
    return {k: observation.get(k) for k in PUBLIC_KEYS}


def detections(view: dict) -> list[tuple[int, int, int]]:
    """World-cell detections (x, y, appearance), sorted deterministically (public order)."""
    ax, ay = view["agent_xy"]
    out = []
    for item in view["visible_objects"]:
        dx, dy, appearance = item[0], item[1], item[2]
        out.append((int(ax) + int(dx), int(ay) + int(dy), int(appearance)))
    return sorted(out, key=lambda d: (d[2], d[0], d[1]))


@dataclass
class Track:
    seq: int
    appearance: int
    sightings: list = field(default_factory=list)  # [(step, x, y)], last two used

    @property
    def track_id(self) -> str:
        return f"trk-{self.seq:05d}"

    def predict(self, step: int, velocity: bool) -> tuple[float, float]:
        s1, x1, y1 = self.sightings[-1]
        if not velocity or len(self.sightings) < 2:
            return float(x1), float(y1)
        s0, x0, y0 = self.sightings[-2]
        dt = s1 - s0
        h = step - s1
        return x1 + (x1 - x0) / dt * h, y1 + (y1 - y0) / dt * h


def assign(dets: list, preds: list, l1_max: float = ASSOCIATION_L1_MAX) -> dict[int, int]:
    """Exhaustive one-to-one association. dets: [(x,y,app)], preds: [(seq, app, (px,py))].

    Returns {det_index: pred_index}. Order: most matches, then least total L1, then
    lexicographically smallest (det order, track sequence) assignment.
    """
    cost = {}
    for i, (x, y, app) in enumerate(dets):
        for j, (_seq, papp, (px, py)) in enumerate(preds):
            if papp == app:
                d = abs(x - px) + abs(y - py)
                if d <= l1_max + 1e-9:
                    cost[i, j] = d
    if not cost:
        return {}
    det_idx = sorted({i for i, _ in cost})
    options = {i: [None] + sorted((j for (a, j) in cost if a == i), key=lambda j: preds[j][0])
               for i in det_idx}
    best_key, best = None, {}
    for combo in itertools.product(*(options[i] for i in det_idx)):
        used = [j for j in combo if j is not None]
        if len(used) != len(set(used)):
            continue
        pairs = {i: j for i, j in zip(det_idx, combo) if j is not None}
        total = sum(cost[i, j] for i, j in pairs.items())
        order = tuple((i, preds[j][0]) for i, j in sorted(pairs.items()))
        key = (-len(pairs), round(total, 9), order)
        if best_key is None or key < best_key:
            best_key, best = key, pairs
    return best


class Tracker:
    """Causal online tracker; ``update`` sees one public frame and returns that frame's output."""

    def __init__(self, baseline: str, *, l1_max: int = ASSOCIATION_L1_MAX,
                 retention_ticks: int = RETENTION_TICKS):
        if baseline not in BASELINES:
            raise ValueError(f"unknown baseline {baseline}")
        self.baseline = baseline
        self.l1_max = l1_max
        self.retention = retention_ticks
        self.tracks: list[Track] = []
        self.next_seq = 1
        self.last_step = None

    def _new(self, det, step):
        t = Track(self.next_seq, det[2], [(step, det[0], det[1])])
        self.next_seq += 1
        self.tracks.append(t)
        return t

    def update(self, observation: dict) -> dict:
        view = public_view(observation)
        step = int(view["step"])
        if self.last_step is not None and step <= self.last_step:
            raise ValueError("frames must arrive in increasing step order")
        self.last_step = step
        dets = detections(view)
        observed = {}
        if self.baseline == "current_only":
            self.tracks = []
            for det in dets:
                observed[self._new(det, step).seq] = det
        else:
            # a track missed on more than `retention` consecutive ticks is lost
            self.tracks = [t for t in self.tracks if step - t.sightings[-1][0] - 1 <= self.retention]
            velocity = self.baseline == "constant_velocity_nn"
            preds = [(t.seq, t.appearance, t.predict(step, velocity)) for t in self.tracks]
            pairs = assign(dets, preds, self.l1_max)
            by_seq = {t.seq: t for t in self.tracks}
            for i, det in enumerate(dets):
                if i in pairs:
                    t = by_seq[preds[pairs[i]][0]]
                    t.sightings = (t.sightings + [(step, det[0], det[1])])[-2:]
                else:
                    t = self._new(det, step)
                observed[t.seq] = det
        out = []
        velocity = self.baseline == "constant_velocity_nn"
        self.tracks = [t for t in self.tracks if step - t.sightings[-1][0] <= self.retention]
        for t in sorted(self.tracks, key=lambda t: t.seq):
            if t.seq in observed:
                x, y, _ = observed[t.seq]
                out.append({"track_id": t.track_id, "appearance": t.appearance, "xy": [float(x), float(y)],
                            "observed": True, "unseen_ticks": 0})
            else:
                px, py = t.predict(step, velocity)
                out.append({"track_id": t.track_id, "appearance": t.appearance, "xy": [px, py],
                            "observed": False, "unseen_ticks": step - t.sightings[-1][0],
                            "reason": "unobserved"})
        return {"step": step, "baseline": self.baseline, "tracks": out}


def run_tracker(baseline: str, public_frames: list[dict], **kw) -> list[dict]:
    tracker = Tracker(baseline, **kw)
    return [tracker.update(frame) for frame in public_frames]
