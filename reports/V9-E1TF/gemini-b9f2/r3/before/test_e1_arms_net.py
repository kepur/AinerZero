def test_arm3_error_lower_than_prior_after_200_steps():
    """Verify Arm 3 achieves strictly lower 10-step error than pure prior after <=200 steps (<=10 s)."""
    start_time = time.perf_counter()

    # Synthetic environment: motion near origin with constant horizontal acceleration bias (0.5 m/s^2)
    dt = 1.0 / 60.0
    T_total = 40
    a_bias = np.array([0.5, 0.0, 0.0], dtype=np.float64)

    env = StaticEnvironment(ground=None)
    true_body = ActiveBody(
        name="body_0",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=np.zeros(3, dtype=np.float64),
        velocity=np.zeros(3, dtype=np.float64),
    )

    true_states = [np.concatenate([true_body.position.copy(), true_body.velocity.copy()])]
    for _ in range(T_total):
        simulate_frame([true_body], env)
        true_body.velocity += a_bias * dt
        true_body.position += a_bias * (0.5 * dt * dt)
        true_states.append(np.concatenate([true_body.position.copy(), true_body.velocity.copy()]))
    true_states = np.array(true_states, dtype=np.float64)

    # Arm 1: Pure Prior rollout from frame 3 (t_start = 3, prefix = frames 0..3)
    t_start = 3
    body_prior = ActiveBody(
        name="body_0",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=true_states[t_start, :3].copy(),
        velocity=true_states[t_start, 3:6].copy(),
    )
    prior_roll = rollout([body_prior], env, num_frames=10)["body_0"]
    prior_pos_10 = prior_roll[10, 0:3]
    error_prior_10 = float(np.linalg.norm(prior_pos_10 - true_states[t_start + 10, :3]))

    # Prepare training dataset for Arm 3 residual network
    # Sliding window of K=4 frames, target is (true_next_state - prior_simulated_next_state)
    K = HISTORY_K
    x_train_list = []
    y_train_list = []
    arm3 = PriorResidualArm(seed=42, learning_rate=1e-2)

    for t in range(K - 1, T_total):
        hist = []
        for k_idx in range(K):
            frame_idx = t - K + 1 + k_idx
            hist.extend(true_states[frame_idx])
        x_train_list.append(hist)

        # Prior residual training target via arm3.training_target
        window = true_states[t - K + 1 : t + 1]
        target = arm3.training_target(window, true_states[t + 1], env)
        y_train_list.append(target)

    batch = {
        "inputs": np.array(x_train_list, dtype=np.float32),
        "targets": np.array(y_train_list, dtype=np.float32),
    }

    # Arm 3 training: <= 200 steps
    num_steps = 120
    assert num_steps <= 200

    for _ in range(num_steps):
        loss_dict = arm3.train_step(batch)

    # Arm 3 prediction from prefix (frames 0..3)
    prefix_data = true_states[: t_start + 1]
    arm3_pred = arm3.predict(prefix_data, env, n_future=10)
    arm3_pos_10 = arm3_pred[10, 0:3]
    error_arm3_10 = float(np.linalg.norm(arm3_pos_10 - true_states[t_start + 10, :3]))

    elapsed = time.perf_counter() - start_time

    assert elapsed <= 10.0, f"Training took too long: {elapsed:.2f} s > 10 s"
    assert error_arm3_10 < error_prior_10, (
        f"Arm 3 error ({error_arm3_10:.6f} m) not lower than pure prior ({error_prior_10:.6f} m)"
    )


def test_arms_training_target_predict_roundtrip_consistency():
    """Verify 1-step roundtrip consistency between training_target() and predict().

    Contract (ainerzero.V9.P79 r2 Claude acceptance criteria):
    - Scene setup must cover:
        1. Multi-body (>= 2 active bodies: body_a and body_b).
        2. Ground plane present (StaticEnvironment with GroundPlane(z_plane=0.0)).
        3. Actual non-default radii != 0.1 (radius_a = 0.25, radius_b = 0.30).
        4. Inter-body collision and ground contact occur within the window.
    - For Arm 2, Arm 3, and Arm 6:
        When a mock network outputs exactly training_target(),
        predict(n_future=1) reproduces the true next-frame state (position and velocity)
        for all scene bodies with L2 error < 1e-6.
    - Mathematical definitions:
        ②: y = s_{t+1} - s_t
        ③: y = s_{t+1} - F_prior(s_t; phi_0, statics)
        ⑥: y = P_perp(phi_hat) * (s_{t+1} - F_prior(s_t; phi_hat, statics))
    - For Arm 6, target must be orthogonal to Jacobian column space (|J^T y| < 1e-8).
    """
    env = StaticEnvironment(ground=GroundPlane(z_plane=0.0))
    radii = {"body_a": 0.25, "body_b": 0.30}

    # Construct K=4 prefix frames for body_a and body_b
    pref_a = np.zeros((4, 13), dtype=np.float64)
    pref_b = np.zeros((4, 13), dtype=np.float64)

    # Historical frames 0..2
    for i in range(3):
        pref_a[i, 0:3] = [-0.03 * (3 - i), 0.0, 0.25]
        pref_a[i, 3:6] = [1.0, 0.0, 0.0]
        pref_a[i, 6] = 1.0

        pref_b[i, 0:3] = [0.50 + 0.03 * (3 - i), 0.0, 0.30]
        pref_b[i, 3:6] = [-1.0, 0.0, 0.0]
        pref_b[i, 6] = 1.0

    # Frame 3 is at t
    pref_a[3, 0:3] = [0.0, 0.0, 0.25]   # Touching ground z=0.0 with r=0.25
    pref_a[3, 3:6] = [1.0, 0.0, 0.0]   # Moving right
    pref_a[3, 6] = 1.0

    pref_b[3, 0:3] = [0.50, 0.0, 0.30]  # Touching ground z=0.0 with r=0.30
    pref_b[3, 3:6] = [-1.0, 0.0, 0.0]  # Moving left (distance 0.50 < r_a + r_b = 0.55 -> collision!)
    pref_b[3, 6] = 1.0

    scene_t = {"body_a": pref_a[3], "body_b": pref_b[3]}
    prefix_dict = {"body_a": pref_a, "body_b": pref_b}

    # Advance scene by 1 step under physical prior via shared scene function
    prior_next, jacobians = _prior_scene_step(
        scene_t,
        radii_by_body=radii,
        params_by_body=None,
        env=env,
        compute_jacobians=True,
    )

    # External physical perturbations
    perturb_a = np.array([0.01, -0.005, 0.02, 0.03, -0.01, 0.02], dtype=np.float64)
    perturb_b = np.array([-0.01, 0.02, -0.01, -0.02, 0.01, 0.01], dtype=np.float64)

    # -------------------------------------------------------------
    # 1. Arm 2 (PureNetArm) Multi-body Roundtrip
    # -------------------------------------------------------------
    arm2 = PureNetArm(seed=42)
    s_next2 = {
        "body_a": prior_next["body_a"][:6] + perturb_a,
        "body_b": prior_next["body_b"][:6] + perturb_b,
    }
    targets2 = arm2.scene_training_targets(scene_t, s_next2, env, radii_by_body=radii)
    # Also verify training_target single-body dispatch matches scene_training_targets
    tar2_a = arm2.training_target(pref_a, s_next2["body_a"], env, body_name="body_a", radii_by_body=radii, scene_states=scene_t)
    assert np.allclose(tar2_a, targets2["body_a"], atol=1e-6)

    class MockNet2:
        def __call__(self, x):
            x_np = np.asarray(x)[0]
            if np.isclose(x_np[-6], 0.0, atol=0.1):
                return mx.array(targets2["body_a"])[None, :]
            return mx.array(targets2["body_b"])[None, :]

    arm2.net = MockNet2()
    pred2 = arm2.predict(prefix_dict, env, n_future=1, radii=radii)
    err2_a = float(np.linalg.norm(pred2["body_a"][1, :6] - s_next2["body_a"]))
    err2_b = float(np.linalg.norm(pred2["body_b"][1, :6] - s_next2["body_b"]))
    assert err2_a < 1e-6, f"Arm 2 body_a roundtrip error {err2_a} >= 1e-6"
    assert err2_b < 1e-6, f"Arm 2 body_b roundtrip error {err2_b} >= 1e-6"

    # -------------------------------------------------------------
    # 2. Arm 3 (PriorResidualArm) Multi-body Roundtrip
    # -------------------------------------------------------------
    arm3 = PriorResidualArm(seed=42)
    s_next3 = {
        "body_a": prior_next["body_a"][:6] + perturb_a,
        "body_b": prior_next["body_b"][:6] + perturb_b,
    }
    targets3 = arm3.scene_training_targets(scene_t, s_next3, env, radii_by_body=radii)
    tar3_a = arm3.training_target(pref_a, s_next3["body_a"], env, body_name="body_a", radii_by_body=radii, scene_states=scene_t)
    assert np.allclose(tar3_a, targets3["body_a"], atol=1e-6)

    class MockNet3:
        def __call__(self, x):
            x_np = np.asarray(x)[0]
            if np.isclose(x_np[-6], 0.0, atol=0.1):
                return mx.array(targets3["body_a"])[None, :]
            return mx.array(targets3["body_b"])[None, :]

    arm3.net = MockNet3()
    pred3 = arm3.predict(prefix_dict, env, n_future=1, radii=radii)
    err3_a = float(np.linalg.norm(pred3["body_a"][1, :6] - s_next3["body_a"]))
    err3_b = float(np.linalg.norm(pred3["body_b"][1, :6] - s_next3["body_b"]))
    assert err3_a < 1e-6, f"Arm 3 body_a roundtrip error {err3_a} >= 1e-6"
    assert err3_b < 1e-6, f"Arm 3 body_b roundtrip error {err3_b} >= 1e-6"

    # -------------------------------------------------------------
    # 3. Arm 6 (IdentifyResidualArm) Multi-body Roundtrip & Orthogonality
    # -------------------------------------------------------------
    arm6 = IdentifyResidualArm(seed=42, project=True)
    # Next states receive unmodelled physical perturbations containing both parallel and orthogonal components
    s_next6 = {
        "body_a": prior_next["body_a"][:6] + perturb_a,
        "body_b": prior_next["body_b"][:6] + perturb_b,
    }

    targets6 = arm6.scene_training_targets(scene_t, s_next6, env, radii_by_body=radii)
    tar6_a = arm6.training_target(pref_a, s_next6["body_a"], env, body_name="body_a", radii_by_body=radii, scene_states=scene_t)
    assert np.allclose(tar6_a, targets6["body_a"], atol=1e-6)

    # Orthogonality checks: target must be orthogonal to each body's Jacobian columns
    dots6_a = np.abs(jacobians["body_a"].T @ targets6["body_a"])
    dots6_b = np.abs(jacobians["body_b"].T @ targets6["body_b"])
    assert float(np.max(dots6_a)) < 1e-8, f"Arm 6 body_a orthogonality violated: {np.max(dots6_a)}"
    assert float(np.max(dots6_b)) < 1e-8, f"Arm 6 body_b orthogonality violated: {np.max(dots6_b)}"

    # When network outputs targets6, predict() applies projection and reproduces projected state
    s_proj6 = {
        "body_a": prior_next["body_a"][:6] + targets6["body_a"],
        "body_b": prior_next["body_b"][:6] + targets6["body_b"],
    }

    class MockNet6:
        def __call__(self, x):
            x_np = np.asarray(x)[0]
            if np.isclose(x_np[-6], 0.0, atol=0.1):
                return mx.array(targets6["body_a"])[None, :]
            return mx.array(targets6["body_b"])[None, :]

    arm6.net = MockNet6()
    pred6 = arm6.predict(prefix_dict, env, n_future=1, radii=radii)
    err6_a = float(np.linalg.norm(pred6["body_a"][1, :6] - s_proj6["body_a"]))
    err6_b = float(np.linalg.norm(pred6["body_b"][1, :6] - s_proj6["body_b"]))
    assert err6_a < 1e-6, f"Arm 6 body_a roundtrip error {err6_a} >= 1e-6"
    assert err6_b < 1e-6, f"Arm 6 body_b roundtrip error {err6_b} >= 1e-6"


