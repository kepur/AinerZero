def test_parameter_count_equality():
    """Verify Arms 2, 3, and 6 have strictly identical parameter counts."""
    arm2 = PureNetArm(seed=DEFAULT_SEED)
    arm3 = PriorResidualArm(seed=DEFAULT_SEED)
    arm6 = IdentifyResidualArm(seed=DEFAULT_SEED)

    count2 = arm2.count_parameters()
    count3 = arm3.count_parameters()
    count6 = arm6.count_parameters()

    assert count2 == REGISTERED_PARAMETER_COUNT
    assert count3 == REGISTERED_PARAMETER_COUNT
    assert count6 == REGISTERED_PARAMETER_COUNT
    assert count2 == count3 == count6


