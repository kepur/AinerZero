# 4. Arm 6 Orthogonal Projection and Diagnostic Variant
# =========================================================================

def test_arm6_orthogonal_projection_inner_product():
    """Verify Arm 6 residual is orthogonal to Jacobian: |·| < 1e-8; failing when project=False."""
    body = ActiveBody(
        name="Ball",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=np.array([0.0, 0.0, 2.0], dtype=np.float64),
        velocity=np.array([1.0, 0.0, -0.5], dtype=np.float64),
    )
    env = StaticEnvironment(ground=None)

    # Compute 1-step Jacobian
    jac_dict = compute_prior_jacobian([body], env, num_frames=1)
    J = np.column_stack([jac_dict[p][1, 0:6] for p in PARAM_NAMES])  # (6, 5)

    raw_residual = np.array([0.15, -0.22, 0.31, 0.08, -0.12, 0.25], dtype=np.float64)

    # 1. Project = True: orthogonal projection
    proj_residual, num_truncated = project_onto_orthogonal_complement(raw_residual, J)

    dots_proj = [abs(float(np.dot(J[:, i], proj_residual))) for i in range(J.shape[1])]
    max_dot_proj = max(dots_proj)
    assert max_dot_proj < 1e-8, f"Max dot product {max_dot_proj} >= 1e-8"
    assert num_truncated >= 0

    # 2. Project = False: raw unprojected residual violates orthogonality
    dots_noproj = [abs(float(np.dot(J[:, i], raw_residual))) for i in range(J.shape[1])]
    max_dot_noproj = max(dots_noproj)
    assert max_dot_noproj > 1e-8, f"Unprojected max dot product {max_dot_noproj} unexpectedly <= 1e-8"


def test_arm6_predict_with_projection_and_diagnostic():
    """Verify Arm 6 predict() records truncated directions, corrections, jacobians and supports project=False."""
    prefix = np.ones((6, 6), dtype=np.float64) * 0.5
    env = StaticEnvironment(ground=None)

    # 1. Arm 6 with projection
    arm6_proj = IdentifyResidualArm(seed=42, project=True)
    traj_proj, info_proj = arm6_proj.predict(prefix, env, n_future=5, return_info=True)
    assert len(info_proj["truncated_counts"]) == 5
    assert all(isinstance(c, int) and c >= 0 for c in info_proj["truncated_counts"])
    assert len(arm6_proj.last_truncated_counts) == 5
    assert len(arm6_proj.last_applied_corrections) == 5
    assert len(arm6_proj.last_jacobians) == 5
    assert len(info_proj["applied_corrections"]) == 5
    assert len(info_proj["jacobians"]) == 5

    # 2. Arm 6 without projection (diagnostic variant)
    arm6_noproj = IdentifyResidualArm(seed=42, project=False)
    traj_noproj, info_noproj = arm6_noproj.predict(prefix, env, n_future=5, return_info=True)
    assert all(c == 0 for c in info_noproj["truncated_counts"])
    assert len(arm6_noproj.last_applied_corrections) == 5
    assert len(arm6_noproj.last_jacobians) == 5


def test_arm6_predict_path_applied_corrections_orthogonality():
    """Verify Arm 6 predict() path actually enforces orthogonality on applied corrections.

    Contract:
    - When project=True, for every step, applied correction c satisfies |J^T c|_inf < 1e-8.
    - When project=False (diagnostic / unprojected), at least one step violates |J^T c|_inf < 1e-8.
    - Captures regressions where the projection branch in predict() is bypassed (e.g. `if False:`).
    """
    prefix = np.ones((6, 6), dtype=np.float64) * 0.5
    env = StaticEnvironment(ground=None)
    n_future = 5

    # 1. Arm 6 with projection enabled (default)
    arm6_proj = IdentifyResidualArm(seed=42, project=True)
    arm6_proj.predict(prefix, env, n_future=n_future)

    assert len(arm6_proj.last_applied_corrections) == n_future
    assert len(arm6_proj.last_jacobians) == n_future

    for step_idx, (c, J) in enumerate(zip(arm6_proj.last_applied_corrections, arm6_proj.last_jacobians)):
        dots = np.abs(J.T @ c)
        max_dot = float(np.max(dots))
        assert max_dot < 1e-8, f"Step {step_idx}: max |J^T c| = {max_dot} >= 1e-8"

    # 2. Arm 6 without projection (project=False)
    arm6_noproj = IdentifyResidualArm(seed=42, project=False)
    arm6_noproj.predict(prefix, env, n_future=n_future)

    assert len(arm6_noproj.last_applied_corrections) == n_future
    assert len(arm6_noproj.last_jacobians) == n_future

    violations = []
    for step_idx, (c, J) in enumerate(zip(arm6_noproj.last_applied_corrections, arm6_noproj.last_jacobians)):
        dots = np.abs(J.T @ c)
        max_dot = float(np.max(dots))
        if max_dot >= 1e-8:
            violations.append((step_idx, max_dot))

    assert len(violations) > 0, "Expected at least one step to violate orthogonality when project=False"


