def test_determinism_seed():
    """Verify identical seeds produce identical parameter SHA256; different seeds differ."""
    seed_a = 42
    seed_b = 999

    arm2_a1 = PureNetArm(seed=seed_a)
    arm2_a2 = PureNetArm(seed=seed_a)
    arm2_b = PureNetArm(seed=seed_b)

    sha2_a1 = arm2_a1.parameter_sha256()
    sha2_a2 = arm2_a2.parameter_sha256()
    sha2_b = arm2_b.parameter_sha256()

    assert sha2_a1 == sha2_a2
    assert sha2_a1 != sha2_b

    arm3_a1 = PriorResidualArm(seed=seed_a)
    arm3_a2 = PriorResidualArm(seed=seed_a)
    arm3_b = PriorResidualArm(seed=seed_b)

    assert arm3_a1.parameter_sha256() == arm3_a2.parameter_sha256()
    assert arm3_a1.parameter_sha256() != arm3_b.parameter_sha256()
    assert arm3_a1.parameter_sha256() == sha2_a1

    arm6_a1 = IdentifyResidualArm(seed=seed_a)
    arm6_a2 = IdentifyResidualArm(seed=seed_a)
    arm6_b = IdentifyResidualArm(seed=seed_b)

    assert arm6_a1.parameter_sha256() == arm6_a2.parameter_sha256()
    assert arm6_a1.parameter_sha256() != arm6_b.parameter_sha256()
    assert arm6_a1.parameter_sha256() == sha2_a1


