def test_observed_prefix_nan_isolation():
    """Verify frames after prefix marked with NaN do not influence prediction."""
    arm = PriorResidualArm(seed=42)

    # Clean prefix of 5 frames
    clean_prefix = np.zeros((5, 6), dtype=np.float64)
    for i in range(5):
        clean_prefix[i, 0] = float(i) * 0.1
        clean_prefix[i, 2] = 2.0 - float(i) * 0.05

    pred_clean = arm.predict(clean_prefix, None, n_future=8)

    # Dirty prefix with trailing NaNs
    dirty_prefix = np.full((12, 6), np.nan, dtype=np.float64)
    dirty_prefix[:5] = clean_prefix

    pred_nan = arm.predict(dirty_prefix, None, n_future=8)

    assert np.array_equal(pred_clean, pred_nan)


