# 3. Arm 3 PriorResidualArm Error Reduction vs Arm 1 (Pure Prior)
# =========================================================================

def test_arm3_error_lower_than_prior_after_200_steps():
    """Verify Arm 3 achieves strictly lower 10-step error than pure prior after <=200 steps (<=10 s)."""
    start_time = time.perf_counter()

    # Synthetic environment: motion near origin with constant horizontal acceleration bias (0.5 m/s^2)
    dt = 1.0 / 60.0
    T_total = 40
    a_bias = np.array([0.5, 0.0, 0.0], dtype=np.float64)

    env = StaticEnvironment(ground=None)
    true_body = ActiveBody(
        name="body_0",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=np.zeros(3, dtype=np.float64),
        velocity=np.zeros(3, dtype=np.float64),
    )

    true_states = [np.concatenate([true_body.position.copy(), true_body.velocity.copy()])]
    for _ in range(T_total):
        simulate_frame([true_body], env)
        true_body.velocity += a_bias * dt
        true_body.position += a_bias * (0.5 * dt * dt)
        true_states.append(np.concatenate([true_body.position.copy(), true_body.velocity.copy()]))
    true_states = np.array(true_states, dtype=np.float64)

    # Arm 1: Pure Prior rollout from frame 3 (t_start = 3, prefix = frames 0..3)
    t_start = 3
    body_prior = ActiveBody(
        name="body_0",
        radius=0.1,
        params=DEFAULT_BIASED_PRIOR.copy(),
        position=true_states[t_start, :3].copy(),
        velocity=true_states[t_start, 3:6].copy(),
    )
    prior_roll = rollout([body_prior], env, num_frames=10)["body_0"]
    prior_pos_10 = prior_roll[10, 0:3]
    error_prior_10 = float(np.linalg.norm(prior_pos_10 - true_states[t_start + 10, :3]))

    # Prepare training dataset for Arm 3 residual network
    # Sliding window of K=4 frames, target is (true_next_state - prior_simulated_next_state)
    K = HISTORY_K
    x_train_list = []
    y_train_list = []
    arm3 = PriorResidualArm(seed=42, learning_rate=1e-2)

    for t in range(K - 1, T_total):
        hist = []
        for k_idx in range(K):
            frame_idx = t - K + 1 + k_idx
            hist.extend(true_states[frame_idx])
        x_train_list.append(hist)

        # Prior residual training target via arm3.training_target
        window = true_states[t - K + 1 : t + 1]
        target = arm3.training_target(window, true_states[t + 1], env)
        y_train_list.append(target)

    batch = {
        "inputs": np.array(x_train_list, dtype=np.float32),
        "targets": np.array(y_train_list, dtype=np.float32),
    }

    # Arm 3 training: <= 200 steps
    num_steps = 120
    assert num_steps <= 200

    for _ in range(num_steps):
        loss_dict = arm3.train_step(batch)

    # Arm 3 prediction from prefix (frames 0..3)
    prefix_data = true_states[: t_start + 1]
    arm3_pred = arm3.predict(prefix_data, env, n_future=10)
    arm3_pos_10 = arm3_pred[10, 0:3]
    error_arm3_10 = float(np.linalg.norm(arm3_pos_10 - true_states[t_start + 10, :3]))

    elapsed = time.perf_counter() - start_time

    assert elapsed <= 10.0, f"Training took too long: {elapsed:.2f} s > 10 s"
    assert error_arm3_10 < error_prior_10, (
        f"Arm 3 error ({error_arm3_10:.6f} m) not lower than pure prior ({error_prior_10:.6f} m)"
    )


def test_arms_training_target_predict_roundtrip_consistency():
    """Verify 1-step roundtrip consistency between training_target() and predict().

    Contract:
    - For Arm 2, Arm 3, and Arm 6, when a mock network outputs exactly training_target(),
      predict(n_future=1) reproduces the true next-frame state (position and velocity)
      with L2 error < 1e-6.
    - Mathematical definitions (一级裁定):
        ②: y = s_{t+1} - s_t
        ③: y = s_{t+1} - F_prior(s_t; phi_0)
        ⑥: y = P_perp(phi_hat) * (s_{t+1} - F_prior(s_t; phi_hat))
    - If Arm 3 target is changed back to s_{t+1} - s_t, roundtrip error is O(dt * g) >> 1e-6 (fails).
    - If Arm 6 projection is removed, training_target fails orthogonality and roundtrip consistency (fails).
    """
    env = StaticEnvironment(ground=None)
    dt = 1.0 / 60.0

    # 1. Arm 2 PureNetArm roundtrip
    arm2 = PureNetArm(seed=42)
    prefix2 = np.zeros((4, 6), dtype=np.float64)
    prefix2[:, 2] = 2.0
    prefix2[:, 0] = np.linspace(0.0, 0.3, 4)
    prefix2[:, 3] = 0.1  # vx = 0.1
    s_t2 = prefix2[-1]
    # Arbitrary next state
    s_next2 = s_t2.copy()
    s_next2[0] += 0.05
    s_next2[2] += 0.02
    s_next2[3] += 0.01

    target2 = arm2.training_target(prefix2, s_next2, env)
    assert np.allclose(target2, s_next2 - s_t2, atol=1e-6)

    class MockNet2:
        def __call__(self, x):
            return mx.array(target2)[None, :]

    arm2.net = MockNet2()
    pred2 = arm2.predict(prefix2, env, n_future=1)
    error2 = float(np.linalg.norm(pred2[1, :6] - s_next2[:6]))
    assert error2 < 1e-6, f"Arm 2 roundtrip error {error2} >= 1e-6"

    # 2. Arm 3 PriorResidualArm roundtrip
    arm3 = PriorResidualArm(seed=42)
    prefix3 = np.zeros((4, 6), dtype=np.float64)
    prefix3[:, 2] = 5.0
    prefix3[:, 3] = 1.0  # vx = 1.0
    s_t3 = prefix3[-1]

    # Compute 1-step prior next state
    b3 = ActiveBody("b3", radius=0.1, params=DEFAULT_BIASED_PRIOR.copy(), position=s_t3[:3].copy(), velocity=s_t3[3:6].copy())
    simulate_frame([b3], env)
    f_prior3 = np.concatenate([b3.position, b3.velocity])

    # True next state with an arbitrary external physical perturbation (e.g. horizontal wind force)
    delta_perturb3 = np.array([0.02, -0.01, 0.03, 0.5 * dt, 0.0, -0.2 * dt], dtype=np.float64)
    s_next3 = f_prior3 + delta_perturb3

    target3 = arm3.training_target(prefix3, s_next3, env)
    assert np.allclose(target3, delta_perturb3, atol=1e-6)

    class MockNet3:
        def __call__(self, x):
            return mx.array(target3)[None, :]

    arm3.net = MockNet3()
    pred3 = arm3.predict(prefix3, env, n_future=1)
    error3 = float(np.linalg.norm(pred3[1, :6] - s_next3[:6]))
    assert error3 < 1e-6, f"Arm 3 roundtrip error {error3} >= 1e-6"

    # 3. Arm 6 IdentifyResidualArm roundtrip & orthogonality
    arm6 = IdentifyResidualArm(seed=42, project=True)
    prefix6 = np.zeros((4, 6), dtype=np.float64)
    prefix6[:, 2] = 3.0
    prefix6[:, 3] = 0.5
    s_t6 = prefix6[-1]

    # Compute Jacobian J at s_t6
    b6 = ActiveBody("b6", radius=0.1, params=DEFAULT_BIASED_PRIOR.copy(), position=s_t6[:3].copy(), velocity=s_t6[3:6].copy())
    jac_dict6 = compute_prior_jacobian([b6], env, num_frames=1, body_index=0)
    J6 = np.column_stack([jac_dict6[p][1, 0:6] for p in PARAM_NAMES])
    simulate_frame([b6], env)
    f_prior6 = np.concatenate([b6.position, b6.velocity])

    # Unmodelled perturbation with both orthogonal and non-orthogonal components
    raw_perturb = np.array([0.05, -0.03, 0.02, 0.04, -0.02, 0.01], dtype=np.float64)
    delta_perp6, _ = arm6.project_residual(raw_perturb, J6)
    s_next6 = f_prior6 + delta_perp6

    target6 = arm6.training_target(prefix6, s_next6, env, prefix_for_identification=prefix6)
    # Target must be orthogonal to Jacobian columns
    dots6 = np.abs(J6.T @ target6)
    max_dot6 = float(np.max(dots6))
    assert max_dot6 < 1e-8, f"Arm 6 target orthogonality violated: {max_dot6} >= 1e-8"

    class MockNet6:
        def __call__(self, x):
            return mx.array(target6)[None, :]

    arm6.net = MockNet6()
    pred6 = arm6.predict(prefix6, env, n_future=1)
    error6 = float(np.linalg.norm(pred6[1, :6] - s_next6[:6]))
    assert error6 < 1e-6, f"Arm 6 roundtrip error {error6} >= 1e-6"

    # Sub-check: If unprojected raw perturbation is passed, training_target must project it
    s_next6_raw = f_prior6 + raw_perturb
    target6_from_raw = arm6.training_target(prefix6, s_next6_raw, env, prefix_for_identification=prefix6)
    dots6_raw = np.abs(J6.T @ target6_from_raw)
    assert float(np.max(dots6_raw)) < 1e-8
    assert np.allclose(target6_from_raw, delta_perp6, atol=1e-6)


